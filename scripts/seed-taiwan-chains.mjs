async function seedTaiwanChains() {
  console.log('🚀 [Seed Taiwan Chains] Starting to seed official chain fanpage deals into database...');

  let insertedCount = 0;

  for (let i = 0; i < CHAIN_DEALS.length; i++) {
    const deal = CHAIN_DEALS[i];
    const dealId = `deal-tw-chain-${i + 1}`;

    const dealData = {
      title: deal.title,
      subtitle: deal.subtitle,
      category: deal.category,
      channelType: deal.channelType,
      merchantName: deal.merchantName,
      merchantLogo: deal.merchantLogo,
      storeBranches: deal.storeBranches,
      regions: deal.regions,
      originalPrice: deal.originalPrice,
      discountPrice: deal.discountPrice,
      priceUnit: deal.priceUnit,
      targetItems: deal.targetItems,
      conditions: deal.conditions,
      eligibleCards: deal.eligibleCards,
      tags: deal.tags,
      startDate: deal.startDate,
      endDate: deal.endDate,
      isHot: deal.isHot,
      isFlashDeal: deal.isFlashDeal,
      source: deal.source,
      sourcePlatform: deal.sourcePlatform,
      sourceUrl: deal.sourceUrl,
      likeCount: Math.floor(Math.random() * 250) + 50,
      commentCount: Math.floor(Math.random() * 40) + 5,
      priceHistory: [
        { date: '昨日', price: deal.originalPrice || 100 },
        { date: '今日', price: deal.discountPrice || 80 },
      ],
      priceDropAlert: {
        isLowest90Days: true,
        isSuspiciousHike: false,
        note: `${deal.merchantName} 官方粉絲團發佈最新特惠！`,
      },
      imageUrl: deal.imageUrl,
      images: deal.images,
      aspectRatio: '4:3',
    };

    try {
      await prisma.deal.upsert({
        where: { id: dealId },
        create: {
          id: dealId,
          ...dealData,
        },
        update: {
          ...dealData,
        },
      });
      insertedCount++;
      console.log(`✅ [${insertedCount}/${CHAIN_DEALS.length}] Upserted: ${deal.merchantName} - ${deal.title}`);
    } catch (err) {
      console.error(`❌ Failed to upsert deal: ${deal.title}`, err.message);
    }
  }

  const totalCount = await prisma.deal.count();
  const merchants = await prisma.deal.groupBy({
    by: ['merchantName'],
    _count: { id: true },
  });

  console.log('\n🎉 [Seed Completed] Database statistics:');
  console.log(`📊 Total Deals in PostgreSQL: ${totalCount}`);
  console.log(`🏢 Unique Brands/Merchants in DB (${merchants.length} 家):`);
  merchants.forEach((m) => {
    console.log(`   - ${m.merchantName}: ${m._count.id} 筆特惠`);
  });
}

seedTaiwanChains()
  .catch((e) => {
    console.error('Fatal seed error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
